def ensure_directories() -> None:
    """Create required output directories."""

    GEOJSON_DIR.mkdir(
        parents=True,
        exist_ok=True,
    )

    MODEL_DIR.mkdir(
        parents=True,
        exist_ok=True,
    )


def require_file(path: Path, description: str) -> None:
    """Fail immediately if an expected source file is missing."""

    if not path.exists():
        raise FileNotFoundError(
            f"Required {description} not found:\n{path}"
        )


def load_geojson(
    path: Path,
    description: str,
) -> gpd.GeoDataFrame:
    """
    Load a GeoJSON dataset and validate its CRS.
    """

    require_file(path, description)

    gdf = gpd.read_file(path)

    if gdf.empty:
        raise ValueError(
            f"{description} is empty:\n{path}"
        )

    if gdf.crs is None:
        raise ValueError(
            f"{description} has no CRS:\n{path}"
        )

    if str(gdf.crs) != EXPECTED_CRS:
        raise ValueError(
            f"{description} has incorrect CRS.\n"
            f"Expected: {EXPECTED_CRS}\n"
            f"Actual:   {gdf.crs}"
        )

    if not gdf.geometry.is_valid.all():
        raise ValueError(
            f"{description} contains invalid geometry."
        )

    return gdf


def export_geojson(
    gdf: gpd.GeoDataFrame,
    filename: str,
) -> Path:
    """
    Export a GeoDataFrame to GeoJSON.

    The source data uses a projected CRS for spatial calculations.
    Web GeoJSON is exported as EPSG:4326 because this is the
    standard geographic CRS expected by most web mapping systems.
    """

    output_path = GEOJSON_DIR / filename

    web_gdf = gdf.to_crs("EPSG:4326")

    web_gdf.to_file(
        output_path,
        driver="GeoJSON",
    )

    return output_path


def copy_if_exists(
    source: Path,
    destination_name: str,
) -> dict[str, Any]:
    """
    Copy an existing 3D model into the web output directory.

    Returns metadata describing whether the model is available.
    """

    destination = MODEL_DIR / destination_name

    if source.exists():
        shutil.copy2(
            source,
            destination,
        )

        return {
            "available": True,
            "file": destination_name,
        }

    return {
        "available": False,
        "file": None,
        "source": str(source),
    }


def load_json_if_exists(
    path: Path,
) -> dict[str, Any] | list[Any] | None:
    """
    Load JSON when available.

    Missing optional metadata does not stop the entire web export.
    """

    if not path.exists():
        return None

    with path.open(
        "r",
        encoding="utf-8",
    ) as file:
        return json.load(file)


def write_json(
    path: Path,
    data: Any,
) -> None:
    """Write formatted JSON."""

    with path.open(
        "w",
        encoding="utf-8",
    ) as file:

        json.dump(
            data,
            file,
            indent=2,
            ensure_ascii=False,
        )


