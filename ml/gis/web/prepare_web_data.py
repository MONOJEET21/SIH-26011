def build_dataset_summary(
    study_area: gpd.GeoDataFrame,
    parcels: gpd.GeoDataFrame,
    buildings: gpd.GeoDataFrame,
    floors: gpd.GeoDataFrame,
    units: gpd.GeoDataFrame,
    underground: gpd.GeoDataFrame,
) -> dict[str, Any]:

    return {
        "study_areas": len(study_area),
        "parcels": len(parcels),
        "buildings": len(buildings),
        "floors": len(floors),
        "property_units": len(units),
        "underground_assets": len(underground),
        "expected_crs": EXPECTED_CRS,
        "web_crs": "EPSG:4326",
    }


# ============================================================
# ENTITY INDEX
# ============================================================

def build_entity_index(
    parcels: gpd.GeoDataFrame,
    buildings: gpd.GeoDataFrame,
    floors: gpd.GeoDataFrame,
    units: gpd.GeoDataFrame,
    underground: gpd.GeoDataFrame,
) -> dict[str, Any]:

    entities: list[dict[str, Any]] = []

    # --------------------------------------------------------
    # PARCELS
    # --------------------------------------------------------

    for _, row in parcels.iterrows():

        parcel_id = str(row["parcel_id"])

        entities.append(
            {
                "entity_type": "PARCEL",
                "entity_id": parcel_id,
                "parent_id": None,
                "display_name": parcel_id,
            }
        )

    # --------------------------------------------------------
    # BUILDINGS
    # --------------------------------------------------------

    for _, row in buildings.iterrows():

        building_id = str(row["building_id"])
        parcel_id = str(row["parcel_id"])

        entities.append(
            {
                "entity_type": "BUILDING",
                "entity_id": building_id,
                "parent_id": parcel_id,
                "display_name": building_id,
            }
        )

    # --------------------------------------------------------
    # FLOORS
    # --------------------------------------------------------

    for _, row in floors.iterrows():

        floor_id = str(row["floor_id"])
        building_id = str(row["building_id"])

        entities.append(
            {
                "entity_type": "FLOOR",
                "entity_id": floor_id,
                "parent_id": building_id,
                "display_name": floor_id,
                "floor_type": str(
                    row.get(
                        "floor_type",
                        "STANDARD",
                    )
                ),
                "z_min": float(row["z_min"]),
                "z_max": float(row["z_max"]),
            }
        )

    # --------------------------------------------------------
    # PROPERTY UNITS
    # --------------------------------------------------------

    for _, row in units.iterrows():

        unit_id = str(row["unit_id"])
        floor_id = str(row["floor_id"])

        entities.append(
            {
                "entity_type": "PROPERTY_UNIT",
                "entity_id": unit_id,
                "parent_id": floor_id,
                "building_id": str(row["building_id"]),
                "z_min": float(row["z_min"]),
                "z_max": float(row["z_max"]),
            }
        )

    # --------------------------------------------------------
    # UNDERGROUND ASSETS
    # --------------------------------------------------------

    for _, row in underground.iterrows():

        asset_id = str(row["asset_id"])
        parcel_id = str(row["parcel_id"])

        entities.append(
            {
                "entity_type": "UNDERGROUND_ASSET",
                "entity_id": asset_id,
                "parent_id": parcel_id,
                "asset_type": str(
                    row.get(
                        "asset_type",
                        "UNKNOWN",
                    )
                ),
                "z_min": float(row["z_min"]),
                "z_max": float(row["z_max"]),
            }
        )

    return {
        "entity_count": len(entities),
        "entities": entities,
    }


# ============================================================
# ULPIN LOOKUP
# ============================================================

def build_ulpin_lookup(
    registry: Any,
) -> dict[str, Any]:

    lookup: dict[str, Any] = {}

    if registry is None:
        return lookup

    records = registry

    if isinstance(registry, dict):

        # Handle common registry structures.
        if "records" in registry:
            records = registry["records"]

        elif "ulpins" in registry:
            records = registry["ulpins"]

        elif "items" in registry:
            records = registry["items"]

    if not isinstance(records, list):
        return lookup

    for record in records:

        if not isinstance(record, dict):
            continue

        ulpin = record.get("ulpin")

        if not ulpin:
            continue

        lookup[str(ulpin)] = record

    return lookup


